// Run: npx -y chrome-devtools-axi run < browser-test.js
// Requires the local preview server on port 8765. Does not run skill evals.
await page.open('http://127.0.0.1:8765');
await page.wait('.repo-card');
const results=[];
async function check(name,fn){const ok=await page.eval(fn);if(!ok)throw Error(name);results.push(name)}
await check('Stage workspace is the default',()=>document.querySelector('.wb-stage-heading h2').textContent.startsWith('Build')&&document.querySelectorAll('[data-skill-card]').length===25);
await page.click('[data-view="compare"]');
await check('Compact capability comparison available',()=>document.querySelector('.decision-table')!==null&&document.querySelectorAll('.decision-table thead th').length===5);
await page.click('[data-view="map"]');
await check('Four repo cards and nine lifecycle rows',()=>document.querySelectorAll('.repo-card').length===4&&document.querySelectorAll('.matrix tbody tr').length===9);
await page.click('[data-map-stage="Verify"]');
await check('Stage inspector shows four columns and pinned evidence',()=>document.querySelector('dialog').open&&document.querySelectorAll('.compare-col').length===4&&document.querySelectorAll('blockquote').length>0&&document.querySelector('.compare-skill a').href.includes('/blob/'));
await page.click('[data-save]');
await check('Shortlist persists',()=>JSON.parse(localStorage.getItem('atlas-shortlist')).length>0);
await page.click('[data-save]');
await page.click('#close-detail');
await page.click('[data-view="overlap"]');
await check('Overlap intersections rendered',()=>document.querySelectorAll('[data-pattern]').length>0);
await page.eval(()=>{const el=document.querySelector('#coverage');el.value='all';el.dispatchEvent(new Event('change'))});
await check('All-four filter has all four present per row',()=>[...document.querySelectorAll('.cap-row')].every(r=>r.querySelectorAll('button.cell').length===4));
await page.eval(()=>{const el=document.querySelector('#coverage');el.value='unique';el.dispatchEvent(new Event('change'))});
await check('Unique filter has exactly one repo per row',()=>document.querySelectorAll('.cap-row').length>0&&[...document.querySelectorAll('.cap-row')].every(r=>r.querySelectorAll('button.cell').length===1));
await page.eval(()=>{const el=document.querySelector('#coverage');el.value='any';el.dispatchEvent(new Event('change'));const mode=document.querySelector('#overlap-mode');mode.value='exact';mode.dispatchEvent(new Event('change'))});
await page.fill('#search','test-driven-development');
await check('Exact-name search',()=>document.querySelectorAll('.cap-row').length===1);
await page.click('[data-group="0"]');
await check('Exact-name source drilldown',()=>document.querySelector('dialog').open&&document.querySelectorAll('.compare-skill').length>=2);
await page.click('#close-detail');
await page.fill('#search','no-such-skill-987654');
await check('Empty state',()=>document.querySelector('.no-results')!==null);
await page.fill('#search','');
await page.click('[data-view="fit"]');
await check('Context recommendations',()=>document.querySelectorAll('.fit-card').length>0);
await page.click('[data-fit="0"]');
await check('Recommendation has actual skills',()=>document.querySelectorAll('.compare-skill').length>0);
await page.click('#close-detail');
await page.click('[data-view="eval"]');
await check('Eval strategy first',()=>document.querySelector('#pilot-estimate').textContent.includes('60'));
await page.click('#show-pilot');
await check('Four eval cases',()=>document.querySelectorAll('[data-case]').length===4);
await check('Unrun ratings are blank',()=>document.querySelector('#total-cursor').textContent==='—');
await page.eval(()=>{for(const input of document.querySelectorAll('[data-score^="cursor:"]')){input.value='4';input.dispatchEvent(new Event('input'))}});
await check('Weighted manual ratings',()=>document.querySelector('#total-cursor').textContent==='4.00');
await page.eval(()=>{const input=document.querySelector('[data-score^="cursor:"]');input.value='9';input.dispatchEvent(new Event('input'))});
await check('Out-of-range rating excluded',()=>document.querySelector('#total-cursor').textContent==='—');
await page.click('#reset-scores');
await page.click('[data-view="map"]');
await page.click('[data-stage="Verify"]');
await check('Stage filter',()=>document.querySelectorAll('.matrix tbody tr').length===1);
await page.click('[data-stage="All"]');
await page.click('#methodology');
await check('Methodology modal',()=>document.querySelector('dialog').open&&document.querySelector('.method-list').textContent.includes('No agent benchmark'));
await page.click('#close-detail');
console.log(JSON.stringify({passed:results.length,checks:results},null,2));
